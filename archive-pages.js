// Restore archived Elementor galleries without removing original slides.
document.addEventListener('DOMContentLoaded', () => {
 document.querySelectorAll('.elementor-widget-image-carousel').forEach(widget => {
  const track=widget.querySelector('.elementor-image-carousel.swiper-wrapper');
  const shell=widget.querySelector('.elementor-image-carousel-wrapper');
  if(!track||!shell)return;
  const slides=Array.from(track.children).filter(el=>el.classList.contains('swiper-slide')&&!el.classList.contains('swiper-slide-duplicate'));
  if(!slides.length)return;
  // Duplicate nodes were generated by Swiper, rather than representing unique original media.
  Array.from(track.children).filter(el=>el.classList.contains('swiper-slide-duplicate')).forEach(el=>el.remove());
  widget.classList.add('archive-carousel-ready');
  track.style.setProperty('transform','none','important');
  track.style.setProperty('transition','none','important');
  shell.tabIndex=0;
  shell.setAttribute('role','region');
  shell.setAttribute('aria-label','Image gallery');
  const dots=Array.from(widget.querySelectorAll('.swiper-pagination-bullet'));
  let index=0,timer=null,touchX=null;
  let settings={};
  try{settings=JSON.parse(widget.getAttribute('data-settings')||'{}')}catch(e){}
  function show(next){
   index=(next+slides.length)%slides.length;
   slides.forEach((slide,i)=>{
    const active=i===index;
    slide.style.setProperty('display',active?'block':'none','important');
    slide.style.setProperty('width',active?'100%':'0','important');
    slide.setAttribute('aria-hidden',String(!active));
    slide.classList.toggle('swiper-slide-active',active);
    slide.classList.toggle('swiper-slide-prev',i===(index-1+slides.length)%slides.length);
    slide.classList.toggle('swiper-slide-next',i===(index+1)%slides.length);
   });
   dots.forEach((dot,i)=>{dot.classList.toggle('swiper-pagination-bullet-active',i===index);dot.setAttribute('aria-current',String(i===index))});
  }
  function stop(){clearInterval(timer);timer=null}
  function play(){
   stop();
   if(settings.autoplay==='yes'&&slides.length>1&&!matchMedia('(prefers-reduced-motion: reduce)').matches)
    timer=setInterval(()=>show(index+1),Math.max(1500,Number(settings.autoplay_speed)||5000));
  }
  function bind(el,fn,label){
   if(!el)return;
   el.setAttribute('role','button');el.tabIndex=0;el.setAttribute('aria-label',label);
   el.addEventListener('click',e=>{e.preventDefault();fn();stop()});
   el.addEventListener('keydown',e=>{if(e.key==='Enter'||e.key===' '){e.preventDefault();fn();stop()}});
  }
  bind(widget.querySelector('.elementor-swiper-button-prev'),()=>show(index-1),'Previous image');
  bind(widget.querySelector('.elementor-swiper-button-next'),()=>show(index+1),'Next image');
  dots.forEach((dot,i)=>bind(dot,()=>show(i),'Go to image '+(i+1)));
  shell.addEventListener('keydown',e=>{if(e.key==='ArrowLeft'||e.key==='ArrowRight'){e.preventDefault();show(index+(e.key==='ArrowRight'?1:-1));stop()}});
  shell.addEventListener('touchstart',e=>{touchX=e.changedTouches[0].screenX},{passive:true});
  shell.addEventListener('touchend',e=>{if(touchX===null)return;const diff=e.changedTouches[0].screenX-touchX;if(Math.abs(diff)>40){show(index+(diff<0?1:-1));stop()}touchX=null},{passive:true});
  if(settings.pause_on_hover==='yes'){shell.addEventListener('mouseenter',stop);shell.addEventListener('mouseleave',play)}
  shell.addEventListener('focusin',stop);
  shell.addEventListener('focusout',e=>{if(!shell.contains(e.relatedTarget))play()});
  show(0);play();
 });
});
// Accessible native lightbox for locally linked images.
document.addEventListener('click',e=>{
 const anchor=e.target.closest('a[href]');
 if(!anchor||!anchor.querySelector('img')||!/\.(jpe?g|png|webp|gif)(\?.*)?$/i.test(anchor.getAttribute('href')||''))return;
 e.preventDefault();
 const dialog=document.createElement('dialog');dialog.className='archive-lightbox';
 const close=document.createElement('button');close.textContent='×';close.type='button';close.setAttribute('aria-label','Close image');
 const img=document.createElement('img');img.src=anchor.href;img.alt=anchor.querySelector('img').alt||'';
 dialog.append(close,img);document.body.append(dialog);
 close.addEventListener('click',()=>dialog.close());
 dialog.addEventListener('click',event=>{if(event.target===dialog)dialog.close()});
 dialog.addEventListener('close',()=>dialog.remove(),{once:true});
 dialog.showModal();close.focus();
});

// Keep every archival slide, and reconnect images when originals are available locally.
document.addEventListener('DOMContentLoaded',()=>{
 document.querySelectorAll('.elementor-image-carousel a[href="#unavailable-asset"]').forEach(a=>{
  const img=a.querySelector('img');if(!img)return;
  let filename='';
  const hash=a.getAttribute('e-action-hash')||'';
  try{
   const segment=decodeURIComponent(hash).split('settings=')[1];
   if(segment)filename=JSON.parse(atob(segment)).url.split('/').pop();
  }catch(err){}
  if(!filename)return;
  const options=['../assets/archive-images/','../assets/','../assets/images/'].map(p=>p+filename);
  let i=0;
  function test(){
   if(i===options.length)return;
   const path=options[i++],probe=new Image();
   probe.onload=()=>{img.src=path;a.href=path;img.classList.remove('swiper-lazy');a.style.pointerEvents='auto'};
   probe.onerror=test;probe.src=path;
  }
  test();
 });
});
